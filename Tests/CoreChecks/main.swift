import Foundation
import CoreGraphics

var passed = 0
func check(_ condition: @autoclosure () -> Bool, _ message: String) {
    guard condition() else { fatalError("FAIL: \(message)") }
    passed += 1
    print("PASS: \(message)")
}

check(BarGeometry.quartzRect(CGRect(x: -1440, y: 900, width: 1440, height: 900), primaryHeight: 900)
      == CGRect(x: -1440, y: -900, width: 1440, height: 900), "副显示器坐标转换")
let screen = CGRect(x: -1512, y: 200, width: 1512, height: 982)
let size = CGSize(width: 440, height: 610)
for anchorX in [-1700.0, -1500, -756, 0, 200] {
    let origin = BarGeometry.panelOrigin(anchor: CGPoint(x: anchorX, y: 1182), size: size, screen: screen, topInset: 38)
    let panel = CGRect(origin: origin, size: size)
    check(screen.contains(panel) && panel.maxY <= screen.maxY - 46, "面板边界与刘海避让 x=\(anchorX)")
}
let primary = CGRect(x: 0, y: 0, width: 1512, height: 982)
let notch = CGRect(x: 660, y: 0, width: 190, height: 38)
check(BarGeometry.isObscured(CGRect(x: 665, y: 0, width: 30, height: 24), screens: [primary], notches: [notch]), "刘海遮挡检测")
check(BarGeometry.isObscured(CGRect(x: -4000, y: 0, width: 30, height: 24), screens: [primary], notches: [notch]), "折叠到屏幕外检测")
check(!BarGeometry.isObscured(CGRect(x: 1200, y: 0, width: 30, height: 24), screens: [primary], notches: [notch]), "可见项目检测")
check(BarGeometry.isObscured(.zero, screens: [primary], notches: [notch]), "零尺寸项目检测")
check(!BarGeometry.isObscured(CGRect(x: -500, y: 0, width: 24, height: 24),
    screens: [CGRect(x: -1920, y: 0, width: 1920, height: 1080)], notches: []), "负坐标显示器不误报")
check(ItemSearch.matches("  电池  ", name: "电池", detail: "控制中心"), "中文搜索与空白")
check(ItemSearch.matches("cloud SYNC", name: "Cloud Drive", detail: "Sync"), "多关键词忽略大小写搜索")
check(!ItemSearch.matches("VPN", name: "电池", detail: "控制中心"), "不匹配的搜索")
check(ItemSearch.matches("", name: "", detail: ""), "空搜索显示全部")
let finder = PinnedApplication(name: "访达", bundleID: "com.apple.finder", bundlePath: "/System/Library/CoreServices/Finder.app")!
let settings = PinnedApplication(name: "设置", bundleID: "com.apple.systempreferences", bundlePath: "/System/Applications/System Settings.app")!
let notes = PinnedApplication(name: "备忘录", bundleID: "com.apple.Notes", bundlePath: "/System/Applications/Notes.app")!
let movedFinder = PinnedApplication(name: "访达", bundleID: "com.apple.finder", bundlePath: "/Applications/Finder.app")!
check(finder.id == movedFinder.id, "应用移动路径后仍以 bundle ID 去重")
check(PinnedApplication(name: "无效", bundleID: "  ", bundlePath: "relative.app") == nil, "拒绝缺少有效标识的应用")
let pathOnly = PinnedApplication(name: "独立应用", bundleID: "", bundlePath: "/Applications/Tools/../Utility.app")!
check(pathOnly.id == "path:/Applications/Utility.app", "无 bundle ID 时使用规范化绝对路径")
var shelf = PinnedShelf(applications: [finder, settings, notes, movedFinder])
check(shelf.applications.map(\.id) == [finder.id, settings.id, notes.id], "恢复列表时去重并保留顺序")
shelf.insert(movedFinder, moveExisting: false)
check(shelf.applications.map(\.id) == [finder.id, settings.id, notes.id], "重复点击固定按钮不会移动或复制应用")
shelf.insert(notes, before: finder.id)
check(shelf.applications.map(\.id) == [notes.id, finder.id, settings.id], "拖到前面图标时向左排序")
shelf.insert(notes, before: settings.id)
check(shelf.applications.map(\.id) == [finder.id, notes.id, settings.id], "拖到后面图标时插入目标前方")
shelf.insert(notes, before: notes.id)
check(shelf.applications.map(\.id) == [finder.id, notes.id, settings.id], "拖回自身保持顺序")
shelf.insert(finder)
check(shelf.applications.map(\.id) == [notes.id, settings.id, finder.id], "重复拖入末尾只移动不复制")
shelf.move(id: finder.id, offset: -1)
check(shelf.applications.map(\.id) == [notes.id, finder.id, settings.id], "右键向左移动")
shelf.move(id: notes.id, offset: -1)
shelf.move(id: settings.id, offset: 1)
shelf.move(id: "missing", offset: 1)
check(shelf.applications.map(\.id) == [notes.id, finder.id, settings.id], "边界及不存在项目移动安全无影响")
let savedShelf = try JSONEncoder().encode(shelf)
let restoredShelf = try JSONDecoder().decode(PinnedShelf.self, from: savedShelf)
check(restoredShelf == shelf, "JSON 恢复应用信息和拖动顺序")
shelf.remove(id: finder.id)
check(shelf.applications.map(\.id) == [notes.id, settings.id], "移除指定应用保留其他顺序")
shelf.remove(id: notes.id)
shelf.remove(id: settings.id)
shelf.move(id: finder.id, offset: -1)
check(shelf.applications.isEmpty, "清空后继续操作不崩溃")
let invalidData = Data("{\"applications\":[{\"name\":\"无效\",\"bundleID\":\"\",\"bundlePath\":\"relative\"}]}".utf8)
let normalizedShelf = try JSONDecoder().decode(PinnedShelf.self, from: invalidData)
check(normalizedShelf.applications.isEmpty, "恢复时过滤无效应用记录")
check((try? JSONDecoder().decode(PinnedShelf.self, from: Data("corrupt".utf8))) == nil, "损坏的偏好数据可回退为空展示栏")
let wifi = MenuItemReference(identifier: "wifi", title: "Wi-Fi", occurrence: 0, wasOnlyItem: false)
let sound = MenuItemReference(identifier: "sound", title: "声音", occurrence: 0, wasOnlyItem: false)
let wifiChanged = MenuItemReference(identifier: "wifi", title: "Wi-Fi：已连接", occurrence: 0, wasOnlyItem: false)
check(wifi.id == wifiChanged.id, "菜单标题变化不改变辅助功能标识")
check(wifi.resolve(in: [sound, wifiChanged]) == 1, "菜单顺序与名称变化后仍定位正确项目")
check(wifi.resolve(in: [sound]) == nil, "目标菜单缺失时不打开同应用的其他菜单")
let menuOne = PinnedApplication(name: "Wi-Fi", bundleID: "com.apple.controlcenter", bundlePath: nil, menuItem: wifi)!
let menuTwo = PinnedApplication(name: "声音", bundleID: "com.apple.controlcenter", bundlePath: nil, menuItem: sound)!
var menuShelf = PinnedShelf(applications: [menuOne, menuTwo])
check(menuShelf.applications.count == 2 && menuOne.applicationID == menuTwo.applicationID, "同一应用的多个菜单可以分别固定")
menuShelf.insert(menuOne)
check(menuShelf.applications.map(\.id) == [menuTwo.id, menuOne.id], "重复拖入菜单移动到末尾且不重复")
let persistedMenus = try JSONDecoder().decode(PinnedShelf.self, from: JSONEncoder().encode(menuShelf))
check(persistedMenus == menuShelf && persistedMenus.applications[0].menuItem == sound, "重启所需菜单标识与顺序完整保存")
let oldSavedData = Data("{\"applications\":[{\"name\":\"访达\",\"bundleID\":\"com.apple.finder\",\"bundlePath\":\"/System/Library/CoreServices/Finder.app\"}]}".utf8)
let upgraded = try JSONDecoder().decode(PinnedShelf.self, from: oldSavedData)
check(upgraded.applications == [finder], "兼容升级前已保存的应用展示栏")
let untitled = MenuItemReference(identifier: "", title: "下载中 50%", occurrence: 0, wasOnlyItem: true)
let finished = MenuItemReference(identifier: "", title: "下载完成", occurrence: 0, wasOnlyItem: true)
check(untitled.resolve(in: [finished]) == 0, "单个无标识菜单支持动态标题")
check(untitled.resolve(in: [finished, sound]) == nil, "多个菜单时不按位置猜测动态标题项目")
let unnamedFirst = MenuItemReference(identifier: "", title: "", occurrence: 0, wasOnlyItem: false)
let unnamedSecond = MenuItemReference(identifier: "", title: "", occurrence: 1, wasOnlyItem: false)
check(unnamedFirst.id != unnamedSecond.id, "同名菜单通过出现序号区分")
check(untitled.runtimeID(processID: 101) == finished.runtimeID(processID: 101), "单个动态标题菜单刷新后保留原图身份")
check(wifi.runtimeID(processID: 101) == wifiChanged.runtimeID(processID: 101), "有标识菜单的标题变化不丢失原图")
check(wifi.runtimeID(processID: 101) != wifi.runtimeID(processID: 102), "不同应用进程不会复用原图")
check(unnamedFirst.runtimeID(processID: 101) != unnamedSecond.runtimeID(processID: 101), "同名多菜单的原图身份互不混用")
let boundary = CGRect(x: 800, y: 0, width: 18, height: 24)
