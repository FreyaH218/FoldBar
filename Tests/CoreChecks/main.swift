check(!NativeLayoutGeometry.matches([CGRect(x: 600, y: 0, width: 24, height: 24)], after: boundary), "拒绝仍在分隔线左侧的选中图标")
check(!NativeLayoutGeometry.matches([.zero], after: boundary), "拒绝零尺寸虚拟菜单项目")
check(!NativeLayoutGeometry.matches([CGRect(x: 818, y: 900, width: 24, height: 24)], after: boundary), "拒绝其他显示器菜单位置")
